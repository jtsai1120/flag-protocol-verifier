#!/usr/bin/env python3
"""Generate a CB18 flag t-FTEC protocol (FPDL + FSE_f/FSE_b qasm) for the
rotated surface code [[d^2,1,d]], d = 2t+1, following Chamberland & Beverland,
"Flag fault-tolerant error correction with arbitrary distance codes",
Quantum 2, 53 (2018), Sec. 3.

* Code: rotated surface code, data qubits row-major on the d x d lattice;
  generator order and qubit order inside each generator match the existing
  protocols/CB_18[[25,1,5]]_plain (Z checks, then X checks, both row-major by
  plaquette).
* FSE_f: serial extraction, one reusable syndrome ancilla and one reusable flag
  ancilla; every weight-4 check uses the Fig. 2(b) single-flag circuit (a
  4-flag circuit, so usable at any distance -- Sec. 3.3); weight-2 checks
  unflagged.  FSE_b: the same without flags.
* Control flow: the general protocol of Sec. 3.1 for t:
    1  same syndrome t-n_diff+1 times in a row, no flags      -> decode(s_prev)
    2  n_diff = t, no flags                                   -> FSE_b, decode
    3  t flags                                                -> FSE_b, decode(flags+s)
    4  m flags (1<=m<t), n_diff = t-m                         -> FSE_b, decode(flags+s)
    5  m flags (1<=m<t), same syndrome t-m-n_diff+1 times     -> decode(flags+s_prev)
  counted exactly as in the existing [[25,1,5]] protocol (n_c_same / n_same
  count equal consecutive pairs, so "k times" means k-1 pairs).
"""
import argparse
from pathlib import Path


def plaquettes(R, C):
    """Return (Z list, X list) for an R x C rotated surface code (row-major data);
    each check is a sorted list of 0-based data qubits."""
    zs, xs = [], []
    for r in range(-1, R):
        for c in range(-1, C):
            qs = [(rr, cc) for rr in (r, r + 1) for cc in (c, c + 1) if 0 <= rr < R and 0 <= cc < C]
            if len(qs) < 2:
                continue
            is_z = (r + c) % 2 != 0
            if len(qs) == 2:
                # boundaries: Z on left/right, X on top/bottom
                vertical = qs[0][1] == qs[1][1]
                if is_z != vertical:
                    continue
            idx = sorted(rr * C + cc for rr, cc in qs)
            (zs if is_z else xs).append(idx)
    return zs, xs


def gen_list(checks, indent):
    rows = []
    for p, qs in checks:
        rows.append("[" + ", ".join(f"{p}{q + 1}" for q in qs) + "]")
    pad = " " * indent
    return "[" + (",\n" + pad + " ").join(rows) + "]"


def qasm(n, d, checks, flagged):
    ns = len(checks)
    nf = sum(1 for _, qs in checks if len(qs) == 4)
    L = ["OPENQASM 3.0;", 'include "stdgates.inc";', ""]
    kind = "flagged" if flagged else "unflagged"
    L += [f"// Serial {kind} extraction for the [[{n},1,{d}]] rotated surface code,",
          "// generated by gen_cb18_surface.py (CB18 Sec. 3, Fig. 2(b) flag circuit).",
          "//   syndrome ancilla: |+> preparation, X-basis measurement",
          "//   Z check: CZ(syn, data); X check: CX(syn -> data)"]
    if flagged:
        L += ["//   flag ancilla: |0> preparation, Z-basis measurement; coupling CX(syn -> flag)"]
    L += [f"qubit[{n}] data;", "qubit syn;"]
    if flagged:
        L.append("qubit flag;")
    L.append(f"bit[{ns}] m;")
    if flagged:
        L.append(f"bit[{nf}] f;")
    L.append("")
    bar = "barrier data,syn,flag;" if flagged else "barrier data,syn;"
    fi = 0
    for i, (p, qs) in enumerate(checks):
        g = "cz" if p == "Z" else "cx"
        name = " ".join(f"{p}{q + 1}" for q in qs)
        if flagged and len(qs) == 4:
            L.append(f"// g{i} = {name}; flag f{fi}.")
            L.append("reset syn; h syn; reset flag;")
            a, b, c, e = qs
            L.append(f"{g} syn,data[{a}]; cx syn,flag; {g} syn,data[{b}];")
            L.append(f"{g} syn,data[{c}]; cx syn,flag; {g} syn,data[{e}];")
            L.append(f"h syn; m[{i}]=measure syn; f[{fi}]=measure flag;")
            fi += 1
        else:
            L.append(f"// g{i} = {name}.")
            L.append("reset syn; h syn;")
            L.append(" ".join(f"{g} syn,data[{q}];" for q in qs))
            L.append(f"h syn; m[{i}]=measure syn;")
        L.append(bar)
        L.append("")
    return "\n".join(L)


def fpdl(n, d, name, checks):
    t = (d - 1) // 2
    ns = len(checks)
    nf = sum(1 for _, qs in checks if len(qs) == 4)
    G8 = gen_list(checks, 8)
    G12 = gen_list(checks, 15)
    tcs = []
    tcs.append((f"((n_c_same == {t + 1} - n_diff - 1 and n_c_same != 0) and n_flag == 0)", "dec_prev"))
    tcs.append((f"(n_diff == {t} and n_flag == 0)", "b_plain"))
    tcs.append((f"(n_flag == {t})", "b_flags"))
    for m in range(1, t):
        tcs.append((f"(n_diff == {t - m} and n_flag == {m})", "b_flags"))
    for m in range(1, t):
        for nd in range(0, t - m):
            tcs.append((f"(n_same == {t - m - nd} and n_diff == {nd} and n_flag == {m})", "flags_prev"))
    bodies = {
        "dec_prev": "{ decode(mr[s_prev]); }",
        "b_plain": "{\n            bit[%d] s = ⊥;\n            (s,) = FSE_b();\n            decode(mr[s]);\n        }" % ns,
        "b_flags": "{\n            bit[%d] s = ⊥;\n            (s,) = FSE_b();\n            m.push(s);\n            decode(m);\n        }" % ns,
        "flags_prev": "{\n            m.push(s_prev);\n            decode(m);\n        }",
    }
    tc_txt = "\n".join(f"        {i + 1}: {c}" for i, (c, _) in enumerate(tcs))
    tp_txt = "\n".join(f"        {i + 1}: {bodies[k]}" for i, (_, k) in enumerate(tcs))
    return f"""protocol {name}:

    code:
        [[{n},1,{d}]]

        {G8}

    se:
        FSE_b {{
            file: "./FSE_b.qasm"
            qd: data
            qm: syn
            g: {G12}
        }}

        FSE_f {{
            file: "./FSE_f.qasm"
            qd: data
            qm: syn
            qf: flag
            g: {G12}
            #-flag: {t}
        }}

    gvar:
        cnt n_c_same = 0;
        cnt n_same = 0;
        cnt n_diff = 0;
        cnt n_flag = 0;

        bit[{ns}] s_prev = ⊥;
        bit diff_prev = 0;
        mr m = mr[];

    tc:
{tc_txt}

    af:
        while(!tc) {{
            bit[{ns}] s = ⊥;
            bit[{nf}] f = ⊥;
            (s, f) = FSE_f();

            if (f != 0) {{
                n_c_same = 0;
                n_same = 0;
                n_flag += 1;
                s_prev = ⊥;
                diff_prev = 0;
                m.push(f);
                continue;
            }}

            if (s_prev != ⊥) {{
                if (diff_prev == 1) {{ diff_prev = 0; }}
                else if (s == s_prev) {{
                    n_c_same += 1;
                    n_same += 1;
                }}
                else {{
                    n_c_same = 0;
                    n_diff += 1;
                    diff_prev = 1;
                }}
            }}
            s_prev = s;
        }}

    tp:
{tp_txt}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("d", type=int, help="rows (and columns unless --cols)")
    ap.add_argument("--cols", type=int, default=None, help="columns for a rectangular d x cols lattice")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    R, C = a.d, a.cols or a.d
    d = min(R, C)
    n = R * C
    zs, xs = plaquettes(R, C)
    checks = [("Z", q) for q in zs] + [("X", q) for q in xs]
    assert len(checks) == n - 1, (len(checks), n)
    name = f"CB18_[[{n},1,{d}]]_gen" + ("" if R == C else f"_{R}x{C}")
    out = Path(a.out) / name
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{name}.fpdl").write_text(fpdl(n, d, name, checks))
    (out / "FSE_f.qasm").write_text(qasm(n, d, checks, True))
    (out / "FSE_b.qasm").write_text(qasm(n, d, checks, False))
    print(out)


if __name__ == "__main__":
    main()
