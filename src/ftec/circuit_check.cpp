std::string CircuitIssue::to_string() const {
    std::string out = kind == Kind::Correctness ? "correctness: "
                      : kind == Kind::Determinism ? "determinism: " : "sign: ";
    if (line) out += "line " + std::to_string(line) + ": ";
    return out + message;
}

std::vector<CircuitIssue> check_circuit(const QasmProgram&              program,
                                        const CircuitRef&               circuit,
                                        const std::vector<std::string>& stabilizers,
                                        const std::vector<std::string>& logicals) {
    std::vector<CircuitIssue> issues;
    const auto add = [&](CircuitIssue::Kind k, std::size_t line, std::string msg) {
        issues.push_back(CircuitIssue{k, line, std::move(msg)});
    };
    using K = CircuitIssue::Kind;

    const Qubits qs = number(program, circuit);
    const auto   syndrome_reg = register_of(program, circuit.syndrome_qubits);
    if (!syndrome_reg) {
        add(K::Correctness, 0, "never measures its qm register '" + circuit.syndrome_qubits + "'");
        return issues;
    }
    const std::size_t width = program.has_bit_register(*syndrome_reg) ? program.bit_width(*syndrome_reg) : 0;
    if (circuit.measures.size() != width) {
        add(K::Correctness, 0,
            "'" + *syndrome_reg + "' has " + std::to_string(width) + " bit(s) but g: declares " +
                std::to_string(circuit.measures.size()) + " generator(s)");
    }

    // Every measurement: deterministic (observes +s), and for the syndrome
    // register, the declared generator.
    std::set<std::size_t> measured;
    for (std::size_t i = 0; i < program.instructions.size(); ++i) {
        const auto& in = program.instructions[i];
        if (in.kind != QasmInstruction::Kind::Measure) continue;
        const std::string label = in.target.reg + "[" + std::to_string(in.target.index) + "]";
        const bool        is_syndrome = in.target.reg == *syndrome_reg;
        if (is_syndrome) measured.insert(in.target.index);

        Pauli observable = Pauli::single(qs.total, qs.index(in.qubits.at(0)), 'Z');
        std::string problem;
        const auto at_start = back_to_start(observable, i, program, qs, false, problem);
        if (!at_start) {
            add(K::Determinism, in.line, label + " " + problem);
            continue;
        }
        const std::string on_data = at_start->letters(0, qs.data);
        if (is_syndrome && in.target.index < circuit.measures.size() &&
            on_data != circuit.measures[in.target.index]) {
            add(K::Correctness, in.line,
                label + " measures " + on_data + ", but g: declares " + circuit.measures[in.target.index]);
            continue;
        }
        const auto sign = group_sign(*at_start, qs.data, stabilizers);
        // g: may write a syndrome row as -[...]: the bit measures minus the
        // code's stabilizer, so it reads 1 without errors, by design.
        const bool declared_minus = is_syndrome && in.target.index < circuit.negated.size() &&
                                    circuit.negated[in.target.index];
        const std::string declared = (declared_minus ? "-" : "") + on_data;
        if (!sign) {
            add(K::Determinism, in.line,
                label + " observes " + on_data + ", which is not a stabilizer: its outcome depends on "
                        "the encoded state");
        } else if (*sign < 0 && !declared_minus) {
            add(K::Sign, in.line,
                label + " observes -" + on_data + ": without errors it reads 1, not 0" +
                    (is_syndrome ? " (write the row as -[...] in g: if that is intended)" : ""));
        } else if (*sign > 0 && declared_minus) {
            add(K::Sign, in.line,
                label + " observes +" + on_data + ": without errors it reads 0, but g: declares " +
                    declared + ", which reads 1");
        }
    }
    for (std::size_t b = 0; b < width; ++b) {
        if (!measured.count(b)) add(K::Correctness, 0, *syndrome_reg + "[" + std::to_string(b) + "] is never measured");
    }

    // Data errors pass through as E' ~ E.
    for (std::size_t j = 0; j < qs.data; ++j) {
        for (const char c : {'X', 'Z'}) {
            Pauli e = Pauli::single(qs.total, j, c);
            for (const auto& in : program.instructions) {
                if (in.kind == QasmInstruction::Kind::Gate) e = conjugate(e, in.gate, operands(in, qs), false);
                else if (in.kind == QasmInstruction::Kind::Reset) {
                    const std::size_t q = qs.index(in.qubits.at(0));
                    e.x[q] = e.z[q] = false;
                }
            }
            Pauli out(qs.total);
            for (std::size_t q = 0; q < qs.data; ++q) { out.x[q] = e.x[q]; out.z[q] = e.z[q]; }
            const Pauli diff = mul(out, Pauli::single(qs.total, j, c));
            if (!group_sign(diff, qs.data, stabilizers)) {
                add(K::Correctness, 0,
                    std::string("an input ") + c + " error on " + qs.name(j) + " leaves as " +
                        out.letters(0, qs.data) + ", which is not the same error up to a stabilizer");
            }
        }
    }

    // Logical operators are preserved, with their signs.
    for (const auto& l : logicals) {
        Pauli       logical = Pauli::from_string(qs.total, l);
        std::string problem;
        const auto  at_start = back_to_start(logical, program.instructions.size(), program, qs, true, problem);
        if (!at_start) {
            add(K::Determinism, 0, "logical " + l + " " + problem + ": the circuit disturbs the encoded state");
            continue;
        }
        Pauli data_part(qs.total);
        for (std::size_t q = 0; q < qs.data; ++q) { data_part.x[q] = at_start->x[q]; data_part.z[q] = at_start->z[q]; }
        data_part.k = at_start->k;
        const auto sign = group_sign(mul(data_part, logical), qs.data, stabilizers);
        if (!sign || *sign < 0) {
            add(sign ? K::Sign : K::Determinism, 0,
                "logical " + l + " comes out as " + (at_start->sign() < 0 ? "-" : "") +
                    at_start->letters(0, qs.data) + ": the circuit changes the encoded state");
        }
    }
    return issues;
}

bool flags_ignore_data(const QasmProgram& program, const CircuitRef& circuit) {
    if (!circuit.flag_qubits) return true;
    const Qubits qs  = number(program, circuit);
    const auto   reg = register_of(program, *circuit.flag_qubits);
    if (!reg) return true;
    for (std::size_t i = 0; i < program.instructions.size(); ++i) {
        const auto& in = program.instructions[i];
        if (in.kind != QasmInstruction::Kind::Measure || in.target.reg != *reg) continue;
        std::string problem;
        const auto at_start = back_to_start(Pauli::single(qs.total, qs.index(in.qubits.at(0)), 'Z'), i,
                                            program, qs, false, problem);
        if (!at_start) return false;
        for (std::size_t q = 0; q < qs.data; ++q) {
            if (!at_start->identity_on(q)) return false;
        }
    }
    return true;
}

std::vector<std::string> logical_operators(const fpdl::CodeSpec& code) {
    spbdd::context ctx(code.n);
    spbdd::code    c(ctx, code.generators);
    std::vector<std::string> out = c.logical_X_operators();
    for (const auto& z : c.logical_Z_operators()) out.push_back(z);
    return out;
}

CircuitReport check_circuits(const Dag& dag) {
    const auto logicals = logical_operators(dag.code);
    CircuitReport report;
    std::set<std::string>    seen;
    for (const auto& node : dag.nodes) {
        if (node.kind != DagNode::Kind::Se) continue;
        const CircuitRef& c = node.circuit;
        std::ostringstream key;
        key << c.qasm.string() << '|' << c.data_qubits << '|' << c.syndrome_qubits << '|'
            << c.flag_qubits.value_or("") << '|';
        for (std::size_t i = 0; i < c.measures.size(); ++i) {
            key << (i < c.negated.size() && c.negated[i] ? "-" : "") << c.measures[i] << ',';
        }
        if (!seen.insert(key.str()).second) continue;

        const std::string where = c.se_name + " (" + c.qasm.filename().string() + ")";
        try {
            const auto program = parse_qasm_file(c.qasm);
            for (const auto& problem : check_circuit(program, c, dag.code.generators, logicals)) {
                // Def. 3.2 / Thm. 3.4 keep signs: an error-free run reads 0
                // on every ancilla and leaves every logical with its sign.
                report.errors.push_back(where + ", " + problem.to_string());
            }
        } catch (const std::exception& error) {
            report.errors.push_back(where + ": " + error.what());
        }
    }
    return report;
}

