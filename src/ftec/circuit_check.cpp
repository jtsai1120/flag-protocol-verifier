// ---------------------------------------------------------------------------
// Signed Pauli operators: P = i^k * prod_j X_j^x_j Z_j^z_j. Hermitian ones
// have k = (number of Y) mod 2, plus 2 for a minus sign; +Y is i X Z.
// ---------------------------------------------------------------------------

struct Pauli {
    std::vector<bool> x, z;
    int               k = 0;

    explicit Pauli(std::size_t n) : x(n, false), z(n, false) {}

    [[nodiscard]] std::size_t size() const { return x.size(); }
    [[nodiscard]] bool        identity_on(std::size_t q) const { return !x[q] && !z[q]; }
    [[nodiscard]] char        letter(std::size_t q) const {
        return x[q] ? (z[q] ? 'Y' : 'X') : (z[q] ? 'Z' : 'I');
    }

    static Pauli single(std::size_t n, std::size_t q, char p) {
        Pauli out(n);
        out.x[q] = p == 'X' || p == 'Y';
        out.z[q] = p == 'Z' || p == 'Y';
        out.k    = p == 'Y' ? 1 : 0;
        return out;
    }

    // From a letter string over the first s.size() qubits, with a + sign.
    static Pauli from_string(std::size_t n, const std::string& s) {
        Pauli out(n);
        for (std::size_t q = 0; q < s.size(); ++q) {
            out.x[q] = s[q] == 'X' || s[q] == 'Y';
            out.z[q] = s[q] == 'Z' || s[q] == 'Y';
            if (s[q] == 'Y') out.k += 1;
        }
        out.k %= 4;
        return out;
    }

    // +1 or -1 for a Hermitian operator, in letter form.
    [[nodiscard]] int sign() const {
        int ny = 0;
        for (std::size_t q = 0; q < size(); ++q) ny += x[q] && z[q];
        return ((k - ny) % 4 + 4) % 4 == 0 ? +1 : -1;
    }

    [[nodiscard]] std::string letters(std::size_t from, std::size_t to) const {
        std::string out;
        for (std::size_t q = from; q < to; ++q) out += letter(q);
        return out;
    }
};

// a * b, with phases.
Pauli mul(const Pauli& a, const Pauli& b) {
    Pauli out(a.size());
    int   swaps = 0;
    for (std::size_t q = 0; q < a.size(); ++q) {
        if (a.z[q] && b.x[q]) ++swaps;      // Z_q X_q = -X_q Z_q
        out.x[q] = a.x[q] != b.x[q];
        out.z[q] = a.z[q] != b.z[q];
    }
    out.k = (a.k + b.k + 2 * swaps) % 4;
    return out;
}

// G P G-dagger for a primitive gate, or G-dagger P G when `inverse`.
Pauli conjugate(const Pauli& p, const std::string& gate, const std::vector<std::size_t>& q,
                bool inverse) {
    if (gate == "i" || gate == "id") return p;
    const std::size_t n = p.size();
    std::string g = gate;
    if (inverse && g == "s") g = "sdg";
    else if (inverse && g == "sdg") g = "s";

    // Images of X_q and Z_q (and of the second qubit's) under the gate.
    std::vector<std::pair<Pauli, Pauli>> images;   // per touched qubit: (img X, img Z)
    const auto P1 = [&](std::size_t a, char c) { return Pauli::single(n, a, c); };
    const auto neg = [](Pauli s) { s.k = (s.k + 2) % 4; return s; };
    if (q.size() == 1) {
        const std::size_t a = q[0];
        if (g == "h") images.push_back({P1(a, 'Z'), P1(a, 'X')});
        else if (g == "s") images.push_back({P1(a, 'Y'), P1(a, 'Z')});
        else if (g == "sdg") images.push_back({neg(P1(a, 'Y')), P1(a, 'Z')});
        else if (g == "x") images.push_back({P1(a, 'X'), neg(P1(a, 'Z'))});
        else if (g == "y") images.push_back({neg(P1(a, 'X')), neg(P1(a, 'Z'))});
        else if (g == "z") images.push_back({neg(P1(a, 'X')), P1(a, 'Z')});
        else throw std::runtime_error("unsupported gate '" + gate + "'");
    } else {
        const std::size_t a = q.at(0), b = q.at(1);
        const auto two = [&](char ca, char cb) { return mul(P1(a, ca), P1(b, cb)); };
        if (g == "cx") images = {{two('X', 'X'), P1(a, 'Z')}, {P1(b, 'X'), two('Z', 'Z')}};
        else if (g == "cz") images = {{two('X', 'Z'), P1(a, 'Z')}, {two('Z', 'X'), P1(b, 'Z')}};
        else if (g == "cy") images = {{two('X', 'Y'), P1(a, 'Z')}, {two('Z', 'X'), two('Z', 'Z')}};
        else if (g == "swap") images = {{P1(b, 'X'), P1(b, 'Z')}, {P1(a, 'X'), P1(a, 'Z')}};
        else throw std::runtime_error("unsupported gate '" + gate + "'");
    }

    Pauli out = p;
    for (const std::size_t t : q) out.x[t] = out.z[t] = false;
    for (std::size_t i = 0; i < q.size(); ++i) {
        if (p.x[q[i]]) out = mul(out, images[i].first);
        if (p.z[q[i]]) out = mul(out, images[i].second);
    }
    return out;
}

// Signed membership in the group generated by +g (commuting, Hermitian), over
// the first `n` qubits: if `p` is in the group up to sign, which sign.
// nullopt: not in the group at all.
std::optional<int> group_sign(const Pauli& p, std::size_t n, const std::vector<std::string>& gens) {
    const std::size_t m = gens.size();
    // Rows: the symplectic vector of each generator, plus which generators
    // it is a product of.
    struct Row { std::vector<bool> v; std::vector<bool> combo; };
    std::vector<Row> rows;
    for (std::size_t i = 0; i < m; ++i) {
        Row r{std::vector<bool>(2 * n, false), std::vector<bool>(m, false)};
        for (std::size_t q = 0; q < n && q < gens[i].size(); ++q) {
            r.v[q]     = gens[i][q] == 'X' || gens[i][q] == 'Y';
            r.v[n + q] = gens[i][q] == 'Z' || gens[i][q] == 'Y';
        }
        r.combo[i] = true;
        rows.push_back(std::move(r));
    }
    std::vector<bool> target(2 * n, false), used(m, false);
    for (std::size_t q = 0; q < n; ++q) {
        target[q]     = p.x[q];
        target[n + q] = p.z[q];
    }
    std::size_t rank = 0;
    for (std::size_t col = 0; col < 2 * n && rank < rows.size(); ++col) {
        std::size_t piv = rank;
        while (piv < rows.size() && !rows[piv].v[col]) ++piv;
        if (piv == rows.size()) continue;
        std::swap(rows[rank], rows[piv]);
        for (std::size_t r = 0; r < rows.size(); ++r) {
            if (r == rank || !rows[r].v[col]) continue;
            for (std::size_t c = 0; c < 2 * n; ++c) rows[r].v[c] = rows[r].v[c] != rows[rank].v[c];
            for (std::size_t c = 0; c < m; ++c) rows[r].combo[c] = rows[r].combo[c] != rows[rank].combo[c];
        }
        if (target[col]) {
            for (std::size_t c = 0; c < 2 * n; ++c) target[c] = target[c] != rows[rank].v[c];
            for (std::size_t c = 0; c < m; ++c) used[c] = used[c] != rows[rank].combo[c];
        }
        ++rank;
    }
    for (const bool b : target) {
        if (b) return std::nullopt;
    }
    // The product of the generators used, with its sign.
    Pauli prod(p.size());
    for (std::size_t i = 0; i < m; ++i) {
        if (used[i]) prod = mul(prod, Pauli::from_string(p.size(), gens[i]));
    }
    // p and prod agree up to a phase; Hermitian both, so it is +1 or -1.
    return ((p.k - prod.k) % 4 + 4) % 4 == 0 ? +1 : -1;
}

// Qubit numbering for one circuit: the data register first, then every other
// register in declaration order.
struct Qubits {
    std::map<std::string, std::size_t> base;
    std::size_t                        data = 0, total = 0;
    const QasmProgram*                 program = nullptr;

    [[nodiscard]] std::size_t index(const QubitRef& r) const { return base.at(r.reg) + r.index; }
    [[nodiscard]] std::string name(std::size_t q) const {
        for (const auto& reg : program->qubits) {
            const std::size_t b = base.at(reg.name);
            if (q >= b && q < b + reg.width) return reg.name + "[" + std::to_string(q - b) + "]";
        }
        return "?";
    }
};

Qubits number(const QasmProgram& program, const CircuitRef& circuit) {
    if (!program.has_qubit_register(circuit.data_qubits)) {
        throw std::runtime_error("no qubit register '" + circuit.data_qubits + "' (qd)");
    }
    Qubits q;
    q.program            = &program;
    q.data               = program.qubit_width(circuit.data_qubits);
    q.base[circuit.data_qubits] = 0;
    q.total              = q.data;
    for (const auto& reg : program.qubits) {
        if (reg.name == circuit.data_qubits) continue;
        q.base[reg.name] = q.total;
        q.total += reg.width;
    }
    return q;
}

std::vector<std::size_t> operands(const QasmInstruction& in, const Qubits& qs) {
    std::vector<std::size_t> out;
    for (const auto& r : in.qubits) out.push_back(qs.index(r));
    return out;
}

// Propagate an operator observed just before instruction `at` back to the
// start of the circuit. A qubit that is measured or reset on the way must
// carry I or Z there (Z: the qubit was in |0>, or holds an earlier outcome);
// `strict` forbids even Z, for operators that must not touch such qubits at
// all. On failure, `problem` says why.
std::optional<Pauli> back_to_start(Pauli p, std::size_t at, const QasmProgram& program,
                                   const Qubits& qs, bool strict, std::string& problem) {
    for (std::size_t j = at; j-- > 0;) {
        const auto& in = program.instructions[j];
        switch (in.kind) {
            case QasmInstruction::Kind::Barrier:
                break;
            case QasmInstruction::Kind::Gate:
                p = conjugate(p, in.gate, operands(in, qs), /*inverse=*/true);
                break;
            case QasmInstruction::Kind::Reset:
            case QasmInstruction::Kind::Measure: {
                const std::size_t q = qs.index(in.qubits.at(0));
                if (p.identity_on(q)) break;
                const char  c     = p.letter(q);
                const bool  reset = in.kind == QasmInstruction::Kind::Reset;
                if (p.x[q] || strict) {
                    problem = std::string(p.x[q] ? "is random: it reads " : "involves ") + c + " on " +
                              qs.name(q) + " right after the " + (reset ? "reset" : "measurement") +
                              " on line " + std::to_string(in.line);
                    return std::nullopt;
                }
                if (!reset) {
                    problem = "depends on the earlier measurement of " + qs.name(q) + " on line " +
                              std::to_string(in.line) + "; reset the qubit before reusing it";
                    return std::nullopt;
                }
                p.z[q] = false;     // +1 on |0>
                break;
            }
        }
    }
    for (std::size_t q = qs.data; q < qs.total; ++q) {
        if (p.identity_on(q)) continue;
        if (p.x[q] || strict) {
            problem = std::string(p.x[q] ? "is random: it reads " : "involves ") + p.letter(q) + " on " +
                      qs.name(q) + ", which starts in |0>";
            return std::nullopt;
        }
        p.z[q] = false;
    }
    return p;
}

std::optional<std::string> register_of(const QasmProgram& program, const std::string& qreg) {
    for (const auto& in : program.instructions) {
        if (in.kind == QasmInstruction::Kind::Measure && in.qubits.at(0).reg == qreg) return in.target.reg;
    }
    return std::nullopt;
}

